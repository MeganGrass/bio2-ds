/* ===========================================================================
 * Cd_init                                                   DS 0x800128c4
 * Reset the ring-buffer slot state, initialise the DS subsystem, set the
 * drive mode, and configure the initial volume.
 * ===========================================================================*/
/* DS 0x800128c4 (Cd_init) */
void Cd_init(void)
{
	ULONG i;
	struct tagCD *pCd = &CD;

	for (i = CD_RING_BUFFERS; i != 0; ) {
		i--;
		pCd->Ring_status[i] = 0;
		pCd->Ring_size[i]   = 0;
	}

	while (DsInit() == 0);

	G.Status_flg &= ~STAT_XA_VOICE;
	DsSetDebug(0);
	DsReadyCallback(NULL);
	DsSyncCallback(NULL);

	while (DsCommand(DslSetmode, &cdmode, NULL, -1) == 0);

	pCd->Cd_rtn_no = 0;
	pCd->Xa_rtn_no = 0;
	pCd->Use_mode  = 0;
	pCd->Vol       = 0x78;
	Cd_set_stereo(1);
}

