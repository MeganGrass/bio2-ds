/* ===========================================================================
 * Xa_control_init  (state 1)                                DS 0x80012cd8
 * Wait until the DS command queue drains, then advance to play state.
 * ===========================================================================*/
/* DS 0x80012cd8 (Xa_control_init) */
void Xa_control_init(void)
{
	UCHAR play_state = 2;

	do
	{
		VSync(0);
		if (DsQueueLen() == 0)
		{
			CD.Xa_rtn_no = play_state;
		}
	} while (CD.Xa_rtn_no != play_state);
}

/* ===========================================================================
 * Xa_seek                                                   DS 0x80012d30
 * (retail-only) DsSyncCallback during the XA seek; once the seek completes
 * and the queue is empty, hands over to Xa_ready_cb.
 * ===========================================================================*/
/* DS 0x80012d30 (Xa_seek) */
void Xa_seek(UCHAR intr, UCHAR *result)
{
	int i;

	/* DS walks result backward with its own pointer; the loop runs for i = 7..0 (pre-decrement test) */
	i = 7;
	result += 7;
	do
	{
		CD.Result[i] = *result--;
	} while (i-- != 0);

	if (intr == DslComplete)
	{
		CD.Limit_break = 0;
		CD.Status++;
		if (DsQueueLen() == 0)
		{
			DsSyncCallback(Xa_ready_cb);
		}
	}
	else
	{
		CD.Status = 0;
	}
}

/* ===========================================================================
 * Xa_ready_cb                                               DS 0x80012dc8
 * (retail-only) DsSyncCallback during XA playback (GetlocP results).
 * ===========================================================================*/
/* DS 0x80012dc8 (Xa_ready_cb) */
void Xa_ready_cb(UCHAR intr, UCHAR *result)
{
	int i;

	/* DS walks result backward with its own pointer; the loop runs for i = 7..0 (pre-decrement test) */
	i = 7;
	result += 7;
	do
	{
		CD.Result[i] = *result--;
	} while (i-- != 0);

	if (intr == DslComplete)
	{
		CD.Status         = 1;
		CD.Limit_break    = 0;
		CD.Result[8]      = 0;
		CD.Current_sector = DsPosToInt((DslLOC *)&CD.Result[5]);
		if (CD.End_sector <= CD.Current_sector)
		{
			CD.Xa_rtn_no = 3;
		}
	}
	else
	{
		CD.Status = 0;
	}
}

/* ===========================================================================
 * Xa_control_play  (state 2)                                DS 0x80012e70
 * Monitor XA playback health and advance to end state on error/timeout.
 * ===========================================================================*/
/* DS 0x80012e70 (Xa_control_play) */
void Xa_control_play(void)
{
	if (DsSystemStatus() == DslReady)
	{
		xacontrol_cdmode ^= 1;
		if (xacontrol_cdmode != 0)
		{
			while (DsCommand(DslGetlocP, NULL, NULL, -1) == 0);
		}
		if (CD.Status == 0)
		{
			CD.Xa_rtn_no = 3;
		}
	}
	if (CD.Current_sector < CD.Start_sector)
	{
		CD.Xa_rtn_no = 3;
	}
	CD.Limit_break++;
	if (CD.Limit_break > 0x3c)
	{
		CD.Xa_rtn_no = 3;
	}
}

/* ===========================================================================
 * Xa_control_end  (state 3)                                 DS 0x80012f48
 * Stop XA transport and ramp volume back down.
 * ===========================================================================*/
/* DS 0x80012f48 (Xa_control_end) */
void Xa_control_end(void)
{
	DsSyncCallback(NULL);

	while (DsCommand(DslPause, NULL, NULL, -1) == 0);

	CD.Xa_rtn_no  = 0;
	G.Status_flg &= ~STAT_XA_VOICE;
	SsSetSerialAttr(SS_SERIAL_A, SS_MIX, SS_SOFF);
	Change_volume(0);
}

/* ===========================================================================
 * Cd_read                                                   DS 0x80012fb8
 * Synchronous (blocking) file read from the CD-ROM.
 * Mode 0/1: read floc[File_no] (0 = VSync wait, 1 = Task_sleep wait).
 * Mode 2/3: CD.Fsize/Fsector/Fsum already set by caller.
 * Returns the number of bytes read.
 * ===========================================================================*/
/* DS 0x80012fb8 (Cd_read) */
ULONG Cd_read(ULONG File_no, ULONG *Address, ULONG Mode, UCHAR *Mess)
{
	ULONG Old_mode;

retry:
	if (Mode < 2)
	{
		CD.Fsum    = floc[File_no].sum;
		CD.Fsize   = floc[File_no].size;
		CD.Fsector = (ULONG)floc[File_no].sec_high * 0x10000 + floc[File_no].sector;
		Old_mode   = Mode;
	}
	else
	{
		Old_mode = Mode - 2;
	}

	Cd_time_out       = 0;
	CD.Cd_rtn_no      = 1;
	CD.Type           = 1;
	CD.Fno            = (USHORT)File_no;
	CD.Fsector_read   = 0;
	CD.Fsize_read     = 0;
	CD.Limit_break    = 0;
	CD.Sum_cnt        = 0;
	CD.Sum            = 0;
	CD.Time_ctr       = 0;
	CD.Fsector_num    = (USHORT)((CD.Fsize + 0x7ff) >> 11);
	CD.Current_sector = CD.Fsector;
	CD.Fsize_now      = CD.Fsize;
	CD.Read_adr       = Address;

	DsFlush();
	DsIntToPos(CD.Current_sector, &CD.Fpos);
	DsSyncCallback(Cd_seek);

	while (DsCommand(DslPause, NULL, NULL, -1) == 0);
	while (DsCommand(DslSetmode, &cdread_cdmode, NULL, -1) == 0);
	while (DsCommand(DslSeekL, &CD.Fpos.minute, NULL, -1) == 0);

	DsReadyCallback(Cd_ready_cb);

	while (DsCommand(DslReadN, &CD.Fpos.minute, NULL, -1) == 0);

	while (1)
	{
		if (DsSystemStatus() == DslReady)
		{
			if ((DsStatus() & DslStatRead) == 0)
			{
				CD.Cd_rtn_no = 6;
			}
			else if (CD.Fsize_now == 0 && CD.Fsector_num == 0)
			{
				if (CD.Sum == CD.Fsum || CD.Check_sum_flg == 1)
				{
					CD.Cd_rtn_no = 0;
				}
				else
				{
					CD.Cd_rtn_no = 4;
				}
				CD.Limit_break = 0;
				while (DsCommand(DslPause, NULL, NULL, -1) == 0);
			}
		}
		else
		{
			Cd_time_out++;
			if (Cd_time_out > 600)
			{
				Cd_time_out_clr = 0;
				CD.Cd_rtn_no    = 6;
			}
		}

		if (Old_mode == 0)
		{
			VSync(0);
		}
		else
		{
			Task_sleep(1);
		}

		if (CD.Cd_rtn_no > 1)
			goto retry;
		if (CD.Cd_rtn_no == 0)
			return CD.Fsize_read;
	}
}

/* ===========================================================================
 * Cd_read_s                                                 DS 0x800132b0
 * Streaming (ring-buffer) file read used for VAB body loads: sectors are
 * read into 12 ring slots by Cd_ready_cb and pushed to the SPU here.
 * Returns CD.Fsize_read on success, 0xFFFFFFFF on SPU transfer failure.
 * ===========================================================================*/
/* DS 0x800132b0 (Cd_read_s) */
ULONG Cd_read_s(ULONG File_no, ULONG Mode, ULONG *Address, ULONG Vab_id, UCHAR *Mess)
{
	ULONG i;
	short Ret;

	while (1)
	{
		if (Mode == 0)
		{
			CD.Fsum    = floc[File_no].sum;
			CD.Fsize   = floc[File_no].size;
			CD.Fsector = (ULONG)floc[File_no].sec_high * 0x10000 + floc[File_no].sector;
		}

		for (i = 0; i < CD_RING_BUFFERS; i++)
		{
			CD.Ring_status[i] = 0;
			CD.Ring_size[i]   = 0;
		}

		UnkCdReadSFlg     = 0;
		CD.Cd_rtn_no      = 1;
		CD.Type           = 2;
		CD.Fno            = (USHORT)File_no;
		CD.Fsector_read   = 0;
		CD.Fsize_read     = 0;
		CD.Limit_break    = 0;
		CD.Sum_cnt        = 0;
		CD.Sum            = 0;
		CD.Write_ctr      = 0;
		CD.Read_ctr       = 0;
		CD.First_flg      = 0;
		CD.Time_ctr       = 0;
		CD.Fsector_num    = (USHORT)((CD.Fsize + 0x7ff) >> 11);
		CD.Current_sector = CD.Fsector;
		CD.Fsize_now      = CD.Fsize;
		CD.Buff_adr       = Address;

		DsFlush();
		DsIntToPos(CD.Current_sector, &CD.Fpos);
		DsSyncCallback(Cd_seek);

		while (DsCommand(DslPause, NULL, NULL, -1) == 0);
		while (DsCommand(DslSetmode, &cdread_s_cdmode, NULL, -1) == 0);
		while (DsCommand(DslSeekL, &CD.Fpos.minute, NULL, -1) == 0);

		DsReadyCallback(Cd_ready_cb);

		while (DsCommand(DslReadN, &CD.Fpos.minute, NULL, -1) == 0);

		while (1)
		{
			if (DsSystemStatus() == DslReady)
			{
				if ((DsStatus() & DslStatRead) == 0)
				{
					CD.Cd_rtn_no = 6;
				}
				else if (CD.Fsize_now == 0 && CD.Fsector_num == 0)
				{
					if (CD.Sum == CD.Fsum)
					{
						CD.Cd_rtn_no = 0;
					}
					else
					{
						CD.Cd_rtn_no = 4;
					}
					CD.Limit_break = 0;
					while (DsCommand(DslPause, NULL, NULL, -1) == 0);
				}
			}

			/* push every filled ring slot to the SPU */
			while (CD.Ring_status[CD.Write_ctr] != 0)
			{
				if (CD.First_flg == 0)
				{
					CD.First_flg = 1;
				}
				else
				{
					UnkCdReadSFlg = 0;
					while (SsVabTransCompleted(SS_IMEDIATE) == 0)
					{
						if (UnkCdReadSFlg++ > 3000)
						{
							EnterCriticalSection();
							DeliverEvent(0xf0000009, 0x20);
							ExitCriticalSection();
						}
					}
				}

				Ret = SsVabTransBodyPartly((UCHAR *)(CD.Buff_adr + CD.Write_ctr * 0x200),
										   CD.Ring_size[CD.Write_ctr], (short)Vab_id);

				if (Ret == (long)Vab_id)
				{
					UnkCdReadSFlg = 0;
					while (SsVabTransCompleted(SS_IMEDIATE) == 0)
					{
						if (UnkCdReadSFlg++ > 3000)
						{
							EnterCriticalSection();
							DeliverEvent(0xf0000009, 0x20);
							ExitCriticalSection();
						}
					}
				}

				if (Ret == -1)
				{
					DsSyncCallback(NULL);
					DsReadyCallback(NULL);
					while (SsVabTransCompleted(SS_IMEDIATE) == 0);
					Task_sleep(0x1e);
					CD.Cd_rtn_no = 0;
					return 0xffffffff;
				}

				CD.Ring_status[CD.Write_ctr] = 0;
				CD.Write_ctr++;
				if (CD.Write_ctr == CD_RING_BUFFERS)
				{
					CD.Write_ctr = 0;
				}
			}

			Task_sleep(1);

			if (CD.Cd_rtn_no > 1)
				break;                  /* retry */
			if (CD.Cd_rtn_no == 0)
				return CD.Fsize_read;
		}
	}
}

/* ===========================================================================
 * Cd_seek                                                   DS 0x80013714
 * DsSyncCallback target during a data read (seek/pause completion).
 * Copies the 8 result bytes into CD.Result and sets CD.Status when intr is
 * DslComplete. Ghidra's auto-prototype (File_no, Mode, Mess) is wrong; the
 * body reads (intr, result).
 * ===========================================================================*/
/* DS 0x80013714 (Cd_seek) */
/* DS walks result backward with its own pointer, tests the pre-decrement counter (loop runs for i = 7..0)
   and sets Status with an if/else, not a comparison value. */
void Cd_seek(UCHAR intr, UCHAR *result)
{
	int i;

	i = 7;
	result += 7;
	do
	{
		CD.Result[i] = *result--;
	} while (i-- != 0);

	if (intr == DslComplete)
	{
		CD.Status = 1;
	}
	else
	{
		CD.Status = 0;
	}
}

/* ===========================================================================
 * Cd_ready_cb                                               DS 0x8001376c
 * DsReadyCallback target during a data read.  Validates the sector header,
 * copies data into the target buffer (Type==1) or into a ring-buffer slot
 * (Type==2) and accumulates the XOR checksum.
 * ===========================================================================*/
/* DS 0x8001376c (Cd_ready_cb) */
void Cd_ready_cb(UCHAR intr, UCHAR *result)
{
	ULONG  read_num;
	ULONG *sum_ck;
	ULONG  i;
	ULONG  Size;

	i        = 4;
	read_num = CD.Read_ctr;

	if (intr == DslDiskError)
	{
		DsSyncCallback(NULL);
		DsReadyCallback(NULL);
		CD.Cd_rtn_no = 2;
		return;
	}
	if (intr != DslDataReady)
		return;

	while (DsGetSector(CD.Work_buf, 3) == 0);

	if (CD.Current_sector != DsPosToInt((DslLOC *)CD.Work_buf))
	{
		CD.Cd_rtn_no = 3;
		return;
	}

	CD.Current_sector++;
	CD.Limit_break = 0;
	CD.Fsector_num--;
	CD.Fsector_read++;

	if (CD.Type == 1)
	{
		if (CD.Fsize_now <= 0x800)
		{
			/* last (partial) sector: read into Work_buf, copy remainder */
			while (DsGetSector(CD.Work_buf, 0x200) == 0);
			sum_ck = (ULONG *)CD.Work_buf;
			Memcpy(CD.Read_adr, CD.Work_buf, CD.Fsize_now);
			Size           = CD.Fsize_now;
			CD.Fsize_now   = 0;
			CD.Fsize_read += Size;
			do
			{
				CD.Sum     ^= (UCHAR)*sum_ck;
				sum_ck     += 0x80;
				CD.Sum_cnt += 0x200;
			} while (CD.Sum_cnt < CD.Fsize_read);
			DsReadyCallback(NULL);
		}
		else
		{
			while (DsGetSector(CD.Read_adr, 0x200) == 0);
			CD.Fsize_now  -= 0x800;
			CD.Fsize_read += 0x800;
			sum_ck = CD.Read_adr;
			do
			{
				CD.Sum     ^= (UCHAR)*sum_ck;
				sum_ck     += 0x80;
				CD.Sum_cnt += 0x200;
			} while (--i != 0);
			CD.Read_adr += 0x200;
		}
	}
	else if (CD.Type == 2)
	{
		if (CD.Ring_status[read_num] != 0)
		{
			CD.Cd_rtn_no = 5;              /* ring overflow */
			return;
		}

		while (DsGetSector(CD.Buff_adr + read_num * 0x200, 0x200) == 0);
		CD.Ring_status[read_num] = 1;

		if (CD.Fsize_now <= 0x800)
		{
			CD.Ring_size[read_num] = (USHORT)CD.Fsize_now;
			Size           = CD.Fsize_now;
			CD.Fsize_now   = 0;
			sum_ck         = CD.Buff_adr + read_num * 0x200;
			CD.Fsize_read += Size;
			do
			{
				CD.Sum     ^= (UCHAR)*sum_ck;
				sum_ck     += 0x80;
				CD.Sum_cnt += 0x200;
			} while (CD.Sum_cnt < CD.Fsize_read);
			DsReadyCallback(NULL);
		}
		else
		{
			CD.Fsize_now          -= 0x800;
			CD.Ring_size[read_num] = 0x800;
			sum_ck                 = CD.Buff_adr + read_num * 0x200;
			CD.Fsize_read         += 0x800;
			do
			{
				CD.Sum     ^= (UCHAR)*sum_ck;
				sum_ck     += 0x80;
				CD.Sum_cnt += 0x200;
			} while (--i != 0);
		}

		CD.Read_ctr++;
		if (CD.Read_ctr == CD_RING_BUFFERS)
		{
			CD.Read_ctr = 0;
		}
	}
}

/* ===========================================================================
 * Cd_set_stereo                                             DS 0x80013a7c
 * Select stereo (mode==1) or mono output, then apply the current volume.
 * ===========================================================================*/
/* DS 0x80013a7c (Cd_set_stereo) */
/* DS sets Stereo_flg with an if/else (store 1 or 0), not a comparison value. */
void Cd_set_stereo(ULONG mode)
{
	if (mode == 1)
	{
		CD.Stereo_flg = 1;
	}
	else
	{
		CD.Stereo_flg = 0;
	}
	Set_volume(CD.Vol);
}

/* ===========================================================================
 * Set_volume                                                DS 0x80013ac8
 * Programme the CD audio mix levels via DsMix.
 * Stereo: L->L / R->R at full 'vol', no cross-mix.
 * Mono:   all four paths at vol/2.
 * ===========================================================================*/
/* DS 0x80013ac8 (Set_volume) */
/* DS stores all four Cdvol bytes directly in each branch; it does not copy val2/val3 into val0/val1 afterwards. */
void Set_volume(ULONG vol)
{
	if (CD.Stereo_flg == 1)
	{
		CD.Cdvol.val0 = (UCHAR)vol;
		CD.Cdvol.val1 = 0;
		CD.Cdvol.val2 = (UCHAR)vol;
		CD.Cdvol.val3 = 0;
	}
	else
	{
		CD.Cdvol.val0 = (UCHAR)(vol >> 1);
		CD.Cdvol.val1 = (UCHAR)(vol >> 1);
		CD.Cdvol.val2 = (UCHAR)(vol >> 1);
		CD.Cdvol.val3 = (UCHAR)(vol >> 1);
	}
	DsMix(&CD.Cdvol);
}

/* ===========================================================================
 * Change_volume                                             DS 0x80013b4c
 * Ramp the CD volume up (mode != 0) or down (mode == 0).
 * ===========================================================================*/
/* DS 0x80013b4c (Change_volume) */
void Change_volume(ULONG mode)
{
	long i;

	if (mode == 0)
	{
		for (i = (long)CD.Vol; i >= 0; i--)
		{
			Set_volume(i);
		}
	}
	else
	{
		i = 0;
		do
		{
			Set_volume(i);
			i++;
		} while ((ULONG)i <= CD.Vol);
	}
}
