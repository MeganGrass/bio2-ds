/* Show the magazine part for the current weapon. Pl_wep_mag_type[weapon - 1] gives the magazine slot (plus one)
 * in Pl_mag; the enemy's sin-parts list is offset to that part, with an extra step for odd Ids below 10
 * and for Ids 14 and 65. The part's visibility bits (0x41) are then set. */
/* DS 0x80042470 (Mag_set) */
void Mag_set(ENEMY_WORK *pEm)
{
	signed char spd_y;
	UCHAR mag_flg;
	int Type;
	PARTS_W *pP_ptr;
	MATRIX Tm;
	SVECTOR Ts;
	SVECTOR Ts0;

	if (((pEm->Type & 0xfff) != 0) && (Type = Pl_wep_mag_type[(pEm->Type & 0xfff) - 1] - 1, Pl_wep_mag_type[(pEm->Type & 0xfff) - 1] != 0)) {
		pP_ptr = pEm->pSin_parts_ptr + Pl_mag[Type].Parts_no;
		if (((pEm->Id & 1) != 0) && (pEm->Id < 10)) {
			pP_ptr += 4;
		}
		if ((pEm->Id == 14) || (pEm->Id == 65)) {
			pP_ptr++;
		}
		pP_ptr->Be_flg |= 0x41;
		spd_y = Pl_mag[Type].V_y;
		pP_ptr->Timer1 = 1;
		pP_ptr->Timer2 = 0;
		pP_ptr->Timer0 = (short)spd_y;
		mag_flg = Pl_mag[Type].Flg;
		pP_ptr->Cdir_x = 0;
		pP_ptr->Cdir_y = 0;
		pP_ptr->Cdir_z = 0;
		pP_ptr->Timer3 = (USHORT)mag_flg;
		RotMatrix((SVECTOR *)&pP_ptr->Cdir_x, (MATRIX *)pP_ptr->M);
		CompM(&pEm->pSin_parts_ptr[0xb].Workm, (MATRIX *)pP_ptr->M, &pP_ptr->Workm);
		pP_ptr->Old_x = pEm->Ground;
		Ts.vx = 0;
		Ts.vz = 0;
		Ts.vy = Pl_mag[Type].Dir + pEm->Cdir_y;
		RotMatrix(&Ts, &Tm);
		Ts.vy = 0;
		Ts.vx = (short)Pl_mag[Type].V_xz;
		ApplyMatrixSV(&Tm, &Ts, &Ts0);
		pP_ptr->Old_y = Ts0.vx;
		pP_ptr->Old_z = Ts0.vz;
	}
}

