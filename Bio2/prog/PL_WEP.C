			if ((best_part == 2) && (diff_y = (UINT)(UCHAR)pBest_em->D_life_u - (pBest_awe->SubDamage >> tbl_no * 3 & 7), pBest_em->D_life_u = (char)diff_y, diff_y * 0x1000000 < 0)) {
				pBest_em->D_life_u = -1;
			}
			ang_dif = Direction_ck(pEm->Pos_x, pEm->Pos_z, pBest_em->Pos_x, pBest_em->Pos_z);
			ang_dif = ang_dif - pBest_em->Cdir_y;
