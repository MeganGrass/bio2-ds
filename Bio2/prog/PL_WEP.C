								if (ck_min + step <= diff_y)     ck_off = 0;
								ck_ret = Attack_r_ck0((MODEL_WORK *)&pEm->Attribute, (MODEL_WORK *)&pTgt->Attribute, (ATTACK_WORK *)&pAt_work[tbl_no].Off1_x);
