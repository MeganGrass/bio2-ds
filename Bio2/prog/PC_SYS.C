/* DS 0x800398ac (Keyboard_Input) */
ULONG Keyboard_Input(ULONG Length, ULONG Flg)
{
	COM_WORK *pCom;
	ULONG     Mend;
	UCHAR     Code;
	UCHAR     Ch;
	UINT      i;

	pCom = pCom_work;
	Mend = 0;
	if (Keyboard() == 0)
		return 0;

	Code                = pCom->Moji_code;
	pCom->Key_input_flg = 1;

	if (Code == 1)
	{
		pCom->nMoji = 0;
	}
	else if (Length == 0)
	{
		if (Flg == 1)
		{
			pCom->In_buf[pCom->nMoji] = Code;
			/* DS re-reads Moji_code here (lbu v1,0x2d9 after the In_buf store) */
			if (pCom->Moji_code == 2)      { pCom->nMoji = 1; Console_put('A'); }
			else if (pCom->Moji_code == 3) { pCom->nMoji = 1; Console_put('B'); }
			else if (pCom->Moji_code == 4) { pCom->nMoji = 1; Console_put('C'); }
			else if (pCom->Moji_code == 5) { pCom->nMoji = 1; Console_put('D'); }
			else return 0;
		}
		else if (Flg == 0)
		{
			pCom->In_buf[pCom->nMoji] = Code;
			if (pCom->Moji_code == 0x1a)      { pCom->nMoji = 1; Console_put('Y'); }
			else if (pCom->Moji_code == 0x0f) { pCom->nMoji = 1; Console_put('N'); }
			else return 0;
		}
		else if (Flg == 2)
		{
			pCom->nMoji = 1;
		}
		else
		{
			return 0;
		}
	}
	else if (Code != 0x1c)
	{
		if (Code == 0x1d)
		{
			if (pCom->nMoji != 0)
			{
				pCom->Cx--;
				pCom->nMoji--;
				Console_put(' ');
				return 0;
			}
		}
		else if (pCom->nMoji < Length)
		{
			Ch = '*';
			if (Flg == 0)
				Ch = (UCHAR)Get_moji_code(pCom->Moji_code);
			Console_put(Ch);
			pCom->In_buf[pCom->nMoji] = pCom->Moji_code;
			pCom->Cx++;
			pCom->nMoji++;
		}
		return 0;
	}

	Cprint(0, s_Pc_sys_msg_80010ba4, &Mend);

	/* convert every buffered key to its moji code; In_buf[nMoji] becomes the terminator */
	for (i = 0; i < pCom->nMoji; i++)
		pCom->In_buf[i] = (UCHAR)Get_moji_code(pCom->In_buf[i]);
	pCom->In_buf[i] = 0;
	pCom->nMoji               = 0;
	return 1;
}

