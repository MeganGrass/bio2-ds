/* DS 0x8003a5a4 (Console_roll_up) */
void Console_roll_up(void)
{
	COM_WORK *pCom;
	int       i;

	pCom = pCom_work;
	for (i = 0; i < 11; i++)
	{
		Memcpy(pCom->Con_buf[i], pCom->Con_buf[i + 1], 30);
		Memcpy(pCom->Con_col_buf[i], pCom->Con_col_buf[i + 1], 30);
	}
	for (i = 0; i < 30; i++)
	{
		pCom->Con_buf[11][i]     = ' ';
		pCom->Con_col_buf[11][i] = 0;
	}
}

/* DS 0x8003a668 (Console_clr) */
void Console_clr(void)
{
	COM_WORK *pCom;
	UCHAR    *pCon;
	UCHAR    *pCol;
	UINT      i;

	pCom = pCom_work;
	pCon = &pCom->Con_buf[0][0];
	pCol = &pCom->Con_col_buf[0][0];
	for (i = 0; i < 360; i++)
	{
		pCon[i] = ' ';
		pCol[i] = 0;
	}
	pCom->Ccol = 0;
	pCom->Cy   = 0;
	pCom->Cx   = 0;
}

/* DS 0x8003a6ac (Console_trans) */
void Console_trans(ULONG Be_flg)
{
	COM_WORK *pCom;
	UCHAR    *pCon;
	UCHAR    *pCol;
	UCHAR    *pCell;   /* Sp_work[4].Be_flg, 16 bytes per character cell */
	UCHAR    *pEnd;
	ULONG     v;
	UINT      Ch;
	UINT      Uv;
	UCHAR     Cl;
	UCHAR     Cy;
	UCHAR     Cur;

	pCom  = pCom_work;
	pCon  = &pCom->Con_buf[0][0];
	pCol  = &pCom->Con_col_buf[0][0];
	pCell = (UCHAR *)&pCom->Sp_work[4].Be_flg;
	pEnd  = pCell + 360 * 16;

	do {
		Ch = *pCon++;
		pCell[-11] = 0x08;
		pCell[-10] = 0x00;
		pCell[-9]  = 0x0a;
		pCell[-8]  = 0x00;
		Cl = *pCol++;
		*pCell = (UCHAR)Be_flg;
		Uv     = Ch - 0x20;
		v = (((((Uv & 0xffff) >> 5) * 0xa00) & 0xffff) | ((Uv & 0x1f) << 3)) + ((UINT)(Cl + 0x7b40) * 0x10000);
		pCell[-7] = (UCHAR)v;
		pCell[-6] = (UCHAR)(v >> 8);
		pCell[-5] = (UCHAR)(v >> 16);
		pCell[-4] = (UCHAR)(v >> 24);
		pCell += 16;
	} while (pCell < pEnd);

	Cy = pCom->Cy;
	pCom->Sp_work[2].Pos_x = (USHORT)((ULONG)pCom->Cx * 8 + 0x10);
	pCom->Sp_work[2].Pos_y = (USHORT)((ULONG)Cy * 10 + 0x15);
	Cur = pCom->Cursor_disp;
	pCom->Cursor_disp = (Cur + 1) & 0x1f;
	pCom->Sp_work[2].Clut = (USHORT)(pCom->Ccol + 0x7b40);

	if (Be_flg == 0)
		pCom->Sp_work[2].Be_flg = 0;
	else
		pCom->Sp_work[2].Be_flg = pCom->Cursor_disp & 0x10;

	pCom->Sp_work[3].Be_flg = (UCHAR)Be_flg;
}

/* DS 0x8003a794 (Sprite_Trans) */
void Sprite_Trans(ULONG nPacket)
{
	COM_WORK *pCom;
	SP_WORK  *pSp;
	ULONG    *pSpW;    /* the same Sp_work entry as words (DS keeps both cursors live) */
	ULONG    *pEnd;
	SPRT     *pPkt;    /* SPRT packet cursor: Packet[Cbuf][0] */
	SPRT     *pNext;
	ULONG    *pPktW;   /* the same packet as words, DS cursor at the rgb+code word */

	pCom  = pCom_work;
	pPkt  = &pCom->Packet[G.Cbuf_id][0];
	pSpW  = (ULONG *)pCom->Sp_work;
	pSp   = pCom->Sp_work;
	pEnd  = pSpW + nPacket * 4;
	pPktW = (ULONG *)pPkt + 1;

	do {
		pNext = pPkt;
		if (pSp->Be_flg != 0)
		{
			/* DS builds every SPRT field pair as one word store (tag, rgb+code, x0/y0, u0/v0/clut, w/h) */
			*(ULONG *)&pPkt->tag = 0x04000000;
			pPktW[0] = (ULONG)pSp->Semi * 0x1000000 + (ULONG)pSp->Col * 0x10101 + 0x64000000;
			pPktW[1] = pSpW[0];
			pPktW[3] = pSpW[1];
			pPktW[2] = pSpW[2];
			pNext = pPkt + 1;
			pPktW += 5;
			AddPrim(&G.Ot1[G.Cbuf_id][pSp->Pri], pPkt);
		}
		pSpW += 4;
		pSp++;
		pPkt = pNext;
	} while (pSpW < pEnd);

	Dr_mode_set();
}

/* DS 0x8003a8cc (Set_sp_work) */
void Set_sp_work(SP_WORK *pSp, SP_WORK *pSw)
{
	/* DS copies the first 8 bytes as two words, adds Clut + 0x7b40 into the high half of the
	   U/V/Clut word, and stores the Pri/Semi/Col/Be_flg word as one word (built from byte loads) */
	*(ULONG *)&pSp->Pos_x = *(ULONG *)&pSw->Pos_x;
	*(ULONG *)&pSp->W     = *(ULONG *)&pSw->W;
	*(ULONG *)&pSp->U     = *(ULONG *)&pSw->U + ((ULONG)pSw->Clut + 0x7b40) * 0x10000;
	*(ULONG *)&pSp->Pri   = (ULONG)pSw->Pri + (ULONG)pSw->Semi * 0x100 + (ULONG)pSw->Col * 0x10000 + (ULONG)pSw->Be_flg * 0x1000000;
}

/* DS 0x8003a92c (Dr_mode_set) */
ULONG Dr_mode_set(void)
{
	COM_WORK *pCom;
	ULONG     Buf;
	int       Slot;   /* OT slot, 7 down to 0 */
	int       i;
	UCHAR    *pDr;

	pCom = pCom_work;
	Buf  = G.Cbuf_id;
	Slot = 7;
	for (i = 0; i < 8; i++)
	{
		pDr = (UCHAR *)&pCom->Dr_mode[G.Cbuf_id][Slot];
		SetDrawMode((DR_MODE *)pDr, 0, 0, 0x85, (RECT *)0);
		Buf = G.Cbuf_id;
		AddPrim(&G.Ot1[Buf][Slot], pDr);
		Slot--;
	}
	return Buf;
}

