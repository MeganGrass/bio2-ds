/* DS 0x8003a298 (Cprint) */
ULONG Cprint(ULONG Speed, UCHAR *pMess, ULONG *Mend)
{
	COM_WORK *pCom;
	int       Tens;
	UCHAR     Printed;

	pCom = pCom_work;
	if (*Mend != 0)
		return 0;

	if (pCom->pMess_start != pMess)
	{
		pCom->pMess_start = pMess;
		pCom->pMess       = pMess;
		pCom->Wait        = 1;
	}
	if (--pCom->Wait != 0)
		return 0;

	pCom->Wait = Speed;
	Printed    = 0;
	/* every character is read through pCom->pMess (DS reloads it); control codes advance it */
	while (*pCom->pMess != 0)
	{
		switch (*pCom->pMess)
		{
		case 0x5d:		/* ']' new line */
			pCom->Cx = 0;
			pCom->Cy++;
			break;

		case 0x5b:		/* '[' + 3 digits: wait count, then stop for this frame */
			pCom->Wait  = (*++pCom->pMess - 0x30) * 100;
			pCom->Wait += (*++pCom->pMess - 0x30) * 10;
			pCom->Wait += *++pCom->pMess - 0x30;
			pCom->pMess++;
			return 0;

		case 0x5e:		/* '^' + 2 digits: move the cursor left */
			Tens      = (*++pCom->pMess - 0x30) * 10;
			pCom->Cx -= Tens + *++pCom->pMess - 0x30;
			break;

		case 0x7c:		/* '|' + 1 digit: text colour */
			pCom->Ccol = *++pCom->pMess - 0x30;
			break;

		default:
			Printed = 1;
			pCom->Con_buf[pCom->Cy][pCom->Cx]     = *pCom->pMess;
			pCom->Con_col_buf[pCom->Cy][pCom->Cx] = pCom->Ccol;
			pCom->Cursor_disp = 0x10;
			pCom->Cx++;
			break;
		}

		if (pCom->Cx > 0x1d)
		{
			pCom->Cx = 0;
			pCom->Cy++;
		}
		if (pCom->Cy > 0xb)
		{
			pCom->Cy--;
			Console_roll_up();
		}
		Snd_se_stad(0x2100000, (VECTOR *)0);

		pCom->pMess++;
		if ((Speed != 0) && (Printed != 0))
			return 0;
	}

	pCom->pMess_start = (UCHAR *)0;
	*Mend = 1;
	return 1;
}

